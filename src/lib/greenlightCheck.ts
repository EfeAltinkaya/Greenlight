// Plain-text Greenlight Check summary for EngageSC paste / printable page. No AI prose except the club-written event summary.
import { BOARDS } from "@/data/rules";
import { fmtDate, lookupDeadline, matchVendor, money, needsNineWeeks, nineWeekReason, requestItems, requestTotal, runChecks, vendorStatus } from "./engine";
import { RULES_VERSION, greenlightVerdict } from "./verdict";
import { requestIdOf } from "./requestId";
import type { Application, Club } from "./types";

export function greenlightCheckText(app: Application, club: Club, today?: string): string {
  const checks = runChecks(app, club, today);
  const v = greenlightVerdict(checks);
  const needsNine = needsNineWeeks(app);
  const dl = lookupDeadline(app.event.date, needsNine, app.submittedAt ?? today);
  const rid = requestIdOf(app);
  const lines: string[] = [];
  lines.push(`GREENLIGHT CHECK`);
  lines.push(`Request ID: ${rid}`);
  lines.push(`Rules: ${RULES_VERSION}`);
  lines.push(`Verdict: ${v.clubLabel}`);
  lines.push("");
  lines.push(`Club: ${club.name}`);
  lines.push(`Event: ${app.event.title}`);
  lines.push(`Board: ${BOARDS[app.event.board].name}`);
  lines.push(`Event date: ${app.event.date ? fmtDate(app.event.date, { weekday: "long", month: "long", day: "numeric", year: "numeric" }) : "(none)"}`);
  lines.push(`Requested: ${money(requestTotal(app))}`);
  lines.push("");
  if (dl.kind === "ok") {
    lines.push(`Deadline used: ${fmtDate(dl.deadline, { weekday: "long", month: "long", day: "numeric", year: "numeric" })} (${dl.uses === "nine" ? "9-week" : "6-week"})`);
    const why = dl.uses === "nine" ? nineWeekReason(app) || "travel or an unlisted food vendor" : "vendors on USG's Vendor List";
    lines.push(`Why: ${why}`);
  } else if (dl.kind === "blackout") {
    lines.push(`Deadline: blackout. ${dl.reason}`);
  } else {
    lines.push(`Deadline: none. ${dl.reason}`);
  }
  lines.push("");
  lines.push(`Event summary (written by the club):`);
  lines.push(app.answers.description.trim() || app.event.description.trim() || "(none yet)");
  lines.push("");
  lines.push(`RULE CHECKS`);
  for (const c of checks) {
    const mark = c.level === "pass" ? "PASS" : c.level === "warn" ? "WARN" : c.level === "fail" ? "FAIL" : "NOTE";
    const heuristic = c.section.startsWith("Greenlight") ? " [Greenlight check, not a USG rule]" : "";
    lines.push(`- [${mark}] ${c.title}${heuristic}`);
    lines.push(`  ${c.section}: "${c.quote}"`);
    if (c.detail) lines.push(`  ${c.detail}`);
  }
  lines.push("");
  lines.push(`VENDOR STATUS (budget lines)`);
  for (const i of requestItems(app)) {
    if (i.category === "food" && i.vendor) {
      const m = matchVendor(i.vendor, "food");
      if (m.kind === "listed") lines.push(`- ${i.item} / ${i.vendor}: ${vendorStatus(m.vendor)}`);
      else lines.push(`- ${i.item} / ${i.vendor}: not on USG's Vendor List`);
    } else if (i.vendor) {
      lines.push(`- ${i.item} / ${i.vendor}: ${i.vendorConfirmed ? "club confirmed approved" : "needs club confirmation (food list only in Greenlight)"}`);
    } else {
      lines.push(`- ${i.item}: no vendor named`);
    }
  }
  lines.push("");
  lines.push(`Generated by Greenlight. The AI never decides money; this check is from the rules engine.`);
  return lines.join("\n");
}
