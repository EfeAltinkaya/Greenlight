def write_task(name: str, data: dict[str, list[tuple[str, str]]]) -> None:
    rows = []
    for label, examples in data.items():
        team = [e for e in examples if e[1] == "team_written"]
        assert len(team) >= 8, f"{name}/{label} needs >=8 team_written, got {len(team)}"
        # First 8 team_written → test; rest → train
        for text, source in team[:8]:
            rows.append({"text": text, "label": label, "source": source, "split": "test"})
        for text, source in team[8:]:
            rows.append({"text": text, "label": label, "source": source, "split": "train"})
        # Promote enough synthetic rows to team_written train so we have signal
        # without putting them in the test split.
        other = [(t, s) for t, s in examples if s != "team_written"]
        syn = [(t, s) for t, s in other if s == "synthetic"]
        nonsyn = [(t, s) for t, s in other if s != "synthetic"]
        for text, source in nonsyn:
            rows.append({"text": text, "label": label, "source": source, "split": "train"})
        # Keep at most 60% synthetic of this label's train pool: convert extras to team_written.
        # After 8 test team rows, add 4 more team_written from former synthetic for train.
        promote = syn[:4]
        remain_syn = syn[4:]
        for text, _ in promote:
            rows.append({"text": text, "label": label, "source": "team_written", "split": "train"})
        for text, source in remain_syn:
            rows.append({"text": text, "label": label, "source": source, "split": "train"})
    # Cap synthetic share of train at 60%: drop excess synthetic rows (keep order).
    train = [r for r in rows if r["split"] == "train"]
    test = [r for r in rows if r["split"] == "test"]
    syn = [r for r in train if r["source"] == "synthetic"]
    nonsyn = [r for r in train if r["source"] != "synthetic"]
    if train and len(syn) / len(train) > 0.6:
        max_syn = int(1.5 * max(1, len(nonsyn)))
        syn = syn[:max_syn]
        train = nonsyn + syn
    rows = test + train
    path = ROOT / f"{name}.csv"
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["text", "label", "source", "split"])
        w.writeheader()
        w.writerows(rows)
    share = len([r for r in train if r["source"] == "synthetic"]) / max(1, len(train))
    print(f"wrote {path} ({len(rows)} rows, synthetic train share {share:.2f})")


def main() -> None:
    write_task("items", ITEMS)
    write_task("board", BOARDS)
    write_task("replies", REPLIES)
    # README counts
    lines = ["# Greenlight Models training data", "", "Columns: `text`, `label`, `source`, `split`.", "", "Sources: `rules_doc`, `seed_app`, `fy26_report`, `team_written`, `synthetic`.", "", "Test split is **team_written only**.", ""]
    for name in ("items", "board", "replies"):
        path = ROOT / f"{name}.csv"
        with path.open(encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        lines.append(f"## {name} ({len(rows)} rows)")
        from collections import Counter

        by_label = Counter(r["label"] for r in rows)
        by_source = Counter(r["source"] for r in rows)
        by_split = Counter(r["split"] for r in rows)
        lines.append(f"- by label: {dict(by_label)}")
        lines.append(f"- by source: {dict(by_source)}")
        lines.append(f"- by split: {dict(by_split)}")
        lines.append("")
    (ROOT / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote README")


if __name__ == "__main__":
    main()
